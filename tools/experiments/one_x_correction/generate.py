"""Generate degree-five/seven, unit-interval BLEP fits to Kaiser-windowed sinc.
Offline only. Constrain residual endpoints exactly, including r(0)=-0.5.
"""
from pathlib import Path
import numpy as np
from scipy.integrate import quad
from scipy.special import i0
ROOT=Path(__file__).resolve().parents[3]
lines=['// Generated by tools/experiments/one_x_correction/generate.py.']
for support,cutoff in ((3,.30),(4,.325),(6,.375)):
    def impulse(x): return 2*cutoff*np.sinc(2*cutoff*x)*i0(6*np.sqrt(max(0,1-(x/support)**2)))/i0(6)
    norm=2*quad(impulse,0,support,epsabs=1e-13)[0]
    def residual(x): return -quad(impulse,x,support,epsabs=1e-13)[0]/norm
    coeff=[]
    for k in range(support):
        t=np.linspace(0,1,257)
        y=np.array([residual(k+z) for z in t]); a=y[0]; b=y[-1]
        # p(t)=a+(b-a)t+t(1-t)q(t), degree five for radius3, seven otherwise.
        basis=np.array([t*(1-t)*t**j for j in range(4 if support==3 else 6)]).T
        q=np.linalg.lstsq(basis,y-a-(b-a)*t,rcond=None)[0]
        p=np.zeros(8);p[0]=a;p[1]=b-a
        for j,v in enumerate(q):p[j+1]+=v;p[j+2]-=v
        coeff.append(p.tolist())
    lines.append(f'pub const KERNEL_{support}: [[f64; 8]; {support}] = [')
    for c in coeff: lines.append('    ['+', '.join(f'{v:.17e}' for v in c)+'],')
    lines.append('];')
(ROOT/'src/oscillators/va/one_x_correction_coefficients.rs').write_text('\n'.join(lines)+'\n')
